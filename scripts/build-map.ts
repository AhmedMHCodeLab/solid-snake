// npm run map: bakes the national plate into web/src/generated/qatar.ts so the browser never needs d3-geo.
import { mkdirSync, writeFileSync } from 'node:fs';
import { graticuleLabels, graticulePathD, nationalAffine, nationalUnitsPerKm, NATIONAL_VIEWBOX, projectNational, qatarPathD } from './lib/projection';

const outline = qatarPathD();
const graticule = graticulePathD();
const labels = graticuleLabels();
const aff = nationalAffine();
const unitsPerKm = Math.round(nationalUnitsPerKm() * 1e4) / 1e4;

// The affine form must agree with d3 to a tenth of a plate unit, or the generated function would drift from the outline.
for (const p of [[50.8, 24.6], [51.2, 25.4], [51.6, 26.15]] as [number, number][]) {
  const [x, y] = projectNational(p);
  const merc = Math.log(Math.tan(Math.PI / 4 + (p[1] * Math.PI) / 360));
  const gx = aff.ax * p[0] + aff.bx;
  const gy = aff.ay * merc + aff.by;
  if (Math.abs(gx - x) > 0.1 || Math.abs(gy - y) > 0.1) throw new Error(`affine drift at ${p}: ${gx},${gy} vs ${x},${y}`);
}

const src = `// GENERATED by scripts/build-map.ts (npm run map). Do not edit. Source: Natural Earth 1:10m, public domain (data/geo/SOURCE.txt).
export const NATIONAL_VIEWBOX = ${JSON.stringify(NATIONAL_VIEWBOX)} as const;
export const QATAR_PATH = ${JSON.stringify(outline)};
export const GRATICULE_PATH = ${JSON.stringify(graticule)};
export const GRATICULE_LABELS: { axis: 'lon' | 'lat'; deg: number; x: number; y: number }[] = ${JSON.stringify(labels)};
/** Plate units per kilometre at the centre of the peninsula, for the scale bar and for sizing regions. */
export const NATIONAL_UNITS_PER_KM = ${unitsPerKm};
const A = ${JSON.stringify({ ax: +aff.ax.toFixed(5), bx: +aff.bx.toFixed(4), ay: +aff.ay.toFixed(5), by: +aff.by.toFixed(4) })};
/** [longitude, latitude] to [x, y] on the national plate. Same result as the build-time d3 projection to 0.1 unit. */
export function projectLonLat([lon, lat]: [number, number]): [number, number] {
  const m = Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
  return [Math.round((A.ax * lon + A.bx) * 10) / 10, Math.round((A.ay * m + A.by) * 10) / 10];
}
`;
mkdirSync(new URL('../web/src/generated/', import.meta.url), { recursive: true });
writeFileSync(new URL('../web/src/generated/qatar.ts', import.meta.url), src);
console.log(`web/src/generated/qatar.ts: outline ${outline.length} chars, graticule ${graticule.length} chars, ${labels.length} labels, ${unitsPerKm} units/km`);
